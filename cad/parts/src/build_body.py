"""Body + electronics bay generator (P3b). Headless, own process:
  python3 build_body.py N OUT.json   (N = stage 1..4)
  solidcraft-cli run OUT.json [--in ../body.solidcraft] --save ../body.solidcraft   (stage 1 has no --in)
Stages: 1 side plates, 2 tray+cradle, 3 covers+lid, 4 mast/mounts/refs/exports. World frame (X fwd, Y left, Z up), mm.
Both sides are generated by a loop over s=+1/-1 (no mirror command, so every body is named).
"""
import json, math, sys
C = []
SUF = ""
def cmd(c, **p): C.append({"command": c, "params": p})
def box(name, x0, x1, y0, y1, z0, z1, op="new", t=None):
    p = dict(length=round(x1-x0, 4), width=round(y1-y0, 4), height=round(z1-z0, 4), corner=[x0, y0, z0], operation=op, name=name if op == "new" else name+SUF)
    if op == "new": p["body_name"] = name
    else: p["targets"] = [t]
    cmd("solid.box", **p)
def cyl(name, d, c, h, axis="Z", op="join", t=None):
    """cylinder of diameter d, base centre c, height h along axis"""
    p = dict(diameter=d, height=h, base=[round(v, 4) for v in c], axis=axis, operation=op, name=name if op == "new" else name+SUF)
    if op == "new": p["body_name"] = name
    else: p["targets"] = [t]
    cmd("solid.cylinder", **p)
def cut(name, t, *a): box(name, *a, op="cut", t=t)
def poly(name, y_far, dist, pts, t, op="join"):
    """polygon in the world XZ plane at y=y_far, extruded toward -Y by dist"""
    cmd("sketch.create", plane={"origin": [0, y_far, 0], "x_dir": [1, 0, 0], "y_dir": [0, 0, 1]}, name=name + SUF + "_sk")
    cmd("sketch.line", points=pts, closed=True, connect=False)
    cmd("sketch.finish")
    cmd("solid.extrude", sketch=name + SUF + "_sk", distance=dist, operation=op, targets=[t], name=name + SUF)
def beam(p0, p1, w):
    (x0, z0), (x1, z1) = p0, p1
    L = math.hypot(x1-x0, z1-z0); nx, nz = -(z1-z0)/L*w/2, (x1-x0)/L*w/2
    return [[x0+nx, z0+nz], [x1+nx, z1+nz], [x1-nx, z1-nz], [x0-nx, z0-nz]]
def Y(s, a, b): return (min(s*a, s*b), max(s*a, s*b))

